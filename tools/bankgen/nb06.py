FUNCS = '''
x_data = [0.0, 1.0, 2.0, 3.0]
y_data = [331.0, 331.6, 332.2, 332.8]
def predict2(w, x):
    return w[0] + w[1] * x
def errorSquared(y, y_pred):
    return (y - y_pred) * (y - y_pred)
def loss(errors):
    return sum(errors)
def gradw0(w, x, y):
    return -2 * (y - (w[0] + x * w[1]))
def gradw1(w, x, y):
    return -2 * (y - (w[0] + x * w[1])) * x
'''
D = '(온도 `x_data = [0.0, 1.0, 2.0, 3.0]` ℃, 속도 `y_data = [331.0, 331.6, 332.2, 332.8]` m/s)'
FN = ('(`predict2(w, x)` 는 `w[0] + w[1] * x`, `gradw0(w, x, y)` 는 `-2 * (y - (w[0] + x * w[1]))`, '
      '`gradw1(w, x, y)` 는 여기에 `x` 를 곱한 값을 돌려준다)')


