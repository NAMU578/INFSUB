    return (f"w = [0.00, 0.00]\nepochs = {n}\nlearning_rate = 0.01\nfor epoch in range(epochs):\n    error = []\n    grad_w0 = []\n    grad_w1 = []\n"
            "    for x, y in zip(x_data, y_data):\n        y_pred = predict2(w, x)\n        error.append(errorSquared(y, y_pred))\n"
            "        grad_w0.append(gradw0(w, x, y))\n        grad_w1.append(gradw1(w, x, y))\n    l = loss(error)\n"
            f"    w[0] = w[0] - learning_rate * sum(grad_w0)\n    w[1] = w[1] - learning_rate * sum(grad_w1)\n{tail}")


